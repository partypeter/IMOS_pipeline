#!/bin/bash
# ------------------------------------------------------------------
#- IMPLEMENTATION
#- author      Hannes Hollmann, National Computational Infrastructure
#- license     GNU General Public License
# ------------------------------------------------------------------
# SYNOPSIS
#    mv_to_prod.sh
#
# DESCRIPTION
#    Moves files from a source path to a mirrored directory structure
#    under a target path.
#
#    For CORDEX DRS folder structures with version folders, it
#    optionally creates "latest" symlink folders alongside
#    version folders (vYYYYMMDD).
#
#    All configuration and PBS flags are set in coordinator.sh.
#    Variables are passed in via the environment (qsub -V).
#    Do not edit this file directly.
#
# WORKFLOW
#    Pass 1 — BFS directory traversal:
#      Walks the source tree breadth-first. At each level, checks
#      whether the corresponding destination directory exists.
#      If not, moves the entire source directory to the destination
#      in one mv operation and stops descending into it. If the
#      destination already exists, enqueues the directory for
#      deeper inspection. After each directory move, scans the
#      just-moved subtree for vYYYYMMDD folders and creates
#      "latest" symlinks where missing (if create_latest_link=true).
#
#    Pass 2 — per-file fallback:
#      Re-scans the source for any remaining regular files and
#      symlinks (i.e. files in directories that already existed
#      at the destination). Moves each file, skipping or
#      overwriting based on the overwrite flag.
#
# VERSION
#    1.0: Initial implementation
#    1.1: Added PBS flags
#    1.2: Reduced log verbosity; exec-based log redirection; summary
#         counters; fixed log directory creation bug
#    1.3: PBS flags and all user configuration moved to coordinator.sh
#    2.0: Replaced flat file loop with two-pass approach:
#         BFS directory moves (pass 1) + per-file fallback (pass 2).
#         Directories missing at the destination are now moved whole,
#         preserving ownership and avoiding unnecessary mkdir calls.
#         latest symlink creation moved to post-move subtree scan.
#
# NOTES / FUTURE IMPROVEMENTS
#    - The "latest" symlink is only created if it does not already
#      exist alongside a vYYYYMMDD folder. It is NOT updated when
#      newer version folders are encountered in the same run, so it
#      may not point to the most recent version if multiple version
#      folders arrive in one run.
#
#    - If two or more vYYYYMMDD folders for the same variable arrive
#      in the same run and are moved as part of a larger directory
#      move in pass 1, only the first one encountered will get a
#      latest symlink (alphabetically, since find output is sorted).
#
#    - Pass 1 loads one directory level at a time into the queue.
#      Pass 2 loads the full remaining file list into memory before
#      processing. For very large numbers of residual files this
#      could be refactored to a streaming approach.
#
#    - The overwrite flag applies to pass 2 (per-file) only. Pass 1
#      directory moves only occur when the destination directory is
#      absent, so there is no conflict to resolve.
#
# ================================================================
# END_OF_HEADER
# ================================================================

# ===============================================================
# MAIN
# ===============================================================

# Create timestamped log file in the log folder set by coordinator.sh
log_file="${log_path}/$(date +%Y%m%d_%H%M%S).log"

# Redirect all output to log file only (PBS output log will be empty)
exec >> "$log_file" 2>&1

myname="${0##*/}"
echo "Starting ${myname} at $(date)"

if [ "$dry_run" = true ]; then
  echo "  [DRY RUN] No files or directories will be moved."
fi

echo ""

# Summary counters
count_dirs_moved=0
count_symlinks_created=0
count_files_moved=0
count_files_overwritten=0
count_files_skipped=0

# -------------------------------------------------------
# PASS 1 — BFS: move whole directories that are missing
#          at the destination
# -------------------------------------------------------

echo "--- Pass 1: directory-level moves (BFS) ---"
echo ""

queue=("$source_path")

while [ ${#queue[@]} -gt 0 ]; do

  current="${queue[0]}"
  queue=("${queue[@]:1}")

  for entry in "$current"/*/; do
    [ -d "$entry" ] || continue
    entry="${entry%/}"

    dst="${entry/$source_path/$target_path}"

    if [ ! -d "$dst" ]; then
      dst_parent="${dst%/*}"
      echo "  [MOVE] ${entry}"
      echo "         -> ${dst_parent}/"
      if [ "$dry_run" = false ]; then
        mv "$entry" "$dst_parent/"
      fi
      (( count_dirs_moved++ ))

      # Scan the just-moved subtree for vYYYYMMDD folders
      # and create latest symlinks where missing
      if [ "$create_latest_link" = true ] && [ "$dry_run" = false ]; then
        while IFS= read -r vdir; do
          vdir_name="${vdir##*/}"
          vdir_parent="${vdir%/*}"
          latest_link="${vdir_parent}/latest"
          if [ ! -L "$latest_link" ]; then
            ln -s "$vdir_name" "$latest_link"
            echo "  [SYMLINK] Created: ${latest_link} -> ${vdir_name}"
            (( count_symlinks_created++ ))
          else
            echo "  [SYMLINK] Already exists: ${latest_link} — skipping"
          fi
        done < <(find "$dst" -type d -name 'v[0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9]' | sort)
      fi

    else
      queue+=("$entry")
    fi

  done

done

echo ""
echo "--- Pass 1 complete ---"
echo "    Directories moved: ${count_dirs_moved}"
echo "    Symlinks created:  ${count_symlinks_created}"
echo ""

# -------------------------------------------------------
# PASS 2 — per-file fallback for remaining source files
#          and symlinks in directories that already exist
#          at the destination
# -------------------------------------------------------

echo "--- Pass 2: file-level moves (remaining source files) ---"
echo ""

while IFS= read -r file; do

  src_dir="${file%/*}"
  filename="${file##*/}"
  dst_dir="${src_dir/$source_path/$target_path}"
  dst_file="${dst_dir}/${filename}"

  if [ ! -d "$dst_dir" ]; then
    # Should not occur after pass 1 — log it if it does
    echo "  [WARN] Destination directory does not exist: ${dst_dir}"
    echo "         ${file} was not moved."
    (( count_files_skipped++ ))
  elif [ -e "${dst_file}" ] && [ "$overwrite" = false ]; then
    echo "  [SKIPPED] ${dst_file}"
    (( count_files_skipped++ ))
  elif [ -e "${dst_file}" ] && [ "$overwrite" = true ]; then
    if [ "$dry_run" = false ]; then
      mv -f "${file}" "${dst_dir}/"
    fi
    echo "  [OVERWRITE] ${dst_file}"
    (( count_files_overwritten++ ))
  else
    if [ "$dry_run" = false ]; then
      mv "${file}" "${dst_dir}/"
    fi
    echo "  [MOVED] ${dst_file}"
    (( count_files_moved++ ))
  fi

done < <(find "$source_path" \( -type f -o -type l \) | sort)

echo ""
echo "--- Pass 2 complete ---"
echo "    Moved:       ${count_files_moved}"
echo "    Overwritten: ${count_files_overwritten}"
echo "    Skipped:     ${count_files_skipped}"
echo ""

echo "Summary:"
echo "  Directories moved (pass 1): ${count_dirs_moved}"
echo "  Symlinks created  (pass 1): ${count_symlinks_created}"
echo "  Files moved       (pass 2): ${count_files_moved}"
echo "  Files overwritten (pass 2): ${count_files_overwritten}"
echo "  Files skipped     (pass 2): ${count_files_skipped}"
echo ""
echo "Completed ${myname} at $(date)"
