#!/bin/bash
# ------------------------------------------------------------------
#- IMPLEMENTATION
#- author      Hannes Hollmann, National Computational Infrastructure
#- license     GNU General Public License
# ------------------------------------------------------------------
# SYNOPSIS
#    mv_to_prod.sh
#
# DESCRIPTION
#    Moves files from a source path to a mirrored directory structure
#    under a target path.
#
#    For CORDEX DRS folder structures with version folders, it
#    optionally creates "latest" symlink folders alongside
#    version folders (vYYYYMMDD).
#
#    All configuration and PBS flags are set in coordinator.sh.
#    Variables are passed in via the environment (qsub -V).
#    Do not edit this file directly.
#
# WORKFLOW
#    Pass 1 — BFS directory traversal:
#      Walks the source tree breadth-first. At each level, checks
#      whether the corresponding destination directory exists.
#      If not, moves the entire source directory to the destination
#      in one mv operation and stops descending into it. If the
#      destination already exists, enqueues the directory for
#      deeper inspection. After each directory move, scans the
#      just-moved subtree for vYYYYMMDD folders and creates
#      "latest" symlinks where missing (if create_latest_link=true).
#
#    Pass 2 — per-file fallback:
#      Re-scans the source for any remaining regular files and
#      symlinks (i.e. files in directories that already existed
#      at the destination). Moves each file, skipping or
#      overwriting based on the overwrite flag.
#
# VERSION
#    1.0: Initial implementation
#    1.1: Added PBS flags
#    1.2: Reduced log verbosity; exec-based log redirection; summary
#         counters; fixed log directory creation bug
#    1.3: PBS flags and all user configuration moved to coordinator.sh
#    2.0: Replaced flat file loop with two-pass approach:
#         BFS directory moves (pass 1) + per-file fallback (pass 2).
#         Directories missing at the destination are now moved whole,
#         preserving ownership and avoiding unnecessary mkdir calls.
#         latest symlink creation moved to post-move subtree scan.
#    2.1: Performance fix for runs where the destination is already
#         substantially populated (so pass 1's whole-directory fast
#         path rarely applies and most files fall through to pass 2):
#         - Pass 1's queue was popped via "queue=(\"${queue[@]:1}\")",
#           which re-slices the whole remaining array on every dequeue
#           (O(n^2) for a large queue). Replaced with an index pointer.
#         - Pass 2 now processes files in parallel batches (xargs -P)
#           instead of one mv per iteration of a single serial loop.
#           Per-file move/skip/overwrite logic, dry_run/overwrite
#           semantics, and log line formats are unchanged; summary
#           counts are now derived from the log's tagged lines after
#           the pass completes, since counters can't be shared across
#           the parallel worker processes.
#    2.2: log_path (a directory the caller wanted a timestamped filename
#         built inside) replaced by log_file (the exact file to write) —
#         the caller now decides the full path, so this script no longer
#         needs to generate its own timestamp.
#    2.3: Fixed dry-run mode re-scanning entire moved-whole subtrees in
#         pass 2. A real run's pass 1 mv makes a moved directory vanish
#         from source_path, so pass 2 never sees its files; dry run skips
#         the mv, so those files were all still there, and every one of
#         them hit the "destination missing" warning path (a nonsensical
#         false positive) — for a large subtree, this could turn a
#         near-instant dry run into one that churns through every file
#         underneath it. Pass 1 now records each directory it logs as
#         "would move" during a dry run, and pass 2's find prunes exactly
#         those paths, mirroring what a real run would already do on its
#         own.
#
# NOTES / FUTURE IMPROVEMENTS
#    - The "latest" symlink is only created if it does not already
#      exist alongside a vYYYYMMDD folder. It is NOT updated when
#      newer version folders are encountered in the same run, so it
#      may not point to the most recent version if multiple version
#      folders arrive in one run.
#
#    - If two or more vYYYYMMDD folders for the same variable arrive
#      in the same run and are moved as part of a larger directory
#      move in pass 1, only the first one encountered will get a
#      latest symlink (alphabetically, since find output is sorted).
#
#    - Pass 2 parallelism/batch size are tunable via pass2_parallel_jobs
#      and pass2_batch_size (set in coordinator.sh; sane defaults apply
#      if unset). Both workers write log lines to the same append-mode
#      log file — safe because each line is a single short write() and
#      POSIX/Lustre guarantee O_APPEND writes below the filesystem block
#      size don't interleave, but this assumption does NOT hold on
#      weaker-consistency network filesystems (e.g. older NFS setups).
#
#    - The overwrite flag applies to pass 2 (per-file) only. Pass 1
#      directory moves only occur when the destination directory is
#      absent, so there is no conflict to resolve.
#
# ================================================================
# END_OF_HEADER
# ================================================================

# ===============================================================
# MAIN
# ===============================================================

# log_file (the exact file to write) is set by coordinator.sh and passed
# in via the environment — nothing to build here.

# Redirect all output to log file only (PBS output log will be empty)
exec >> "$log_file" 2>&1

myname="${0##*/}"
echo "Starting ${myname} at $(date)"

if [ "$dry_run" = true ]; then
  echo "  [DRY RUN] No files or directories will be moved."
fi

echo ""

# Summary counters
count_dirs_moved=0
count_symlinks_created=0
count_files_moved=0
count_files_overwritten=0
count_files_skipped=0

# Dry run only: top-level directories pass 1 logs as "would move" but
# leaves in place. A real mv would make these vanish from source_path
# entirely, so pass 2 would never see their files; dry run has to
# exclude them from its own find below instead (see pass 2), or it
# re-scans everything underneath them and hits a nonsensical
# "destination missing" warning for every single file.
dry_run_pruned_dirs=()

# -------------------------------------------------------
# PASS 1 — BFS: move whole directories that are missing
#          at the destination
# -------------------------------------------------------

echo "--- Pass 1: directory-level moves (BFS) ---"
echo ""

queue=("$source_path")
queue_idx=0

while [ "$queue_idx" -lt ${#queue[@]} ]; do

  current="${queue[$queue_idx]}"
  queue_idx=$((queue_idx + 1))

  for entry in "$current"/*/; do
    [ -d "$entry" ] || continue
    entry="${entry%/}"

    dst="${entry/$source_path/$target_path}"

    if [ ! -d "$dst" ]; then
      dst_parent="${dst%/*}"
      echo "  [MOVE] ${entry}"
      echo "         -> ${dst_parent}/"
      if [ "$dry_run" = false ]; then
        mv "$entry" "$dst_parent/"
      else
        dry_run_pruned_dirs+=("$entry")
      fi
      (( count_dirs_moved++ ))

      # Scan the just-moved subtree for vYYYYMMDD folders
      # and create latest symlinks where missing
      if [ "$create_latest_link" = true ] && [ "$dry_run" = false ]; then
        while IFS= read -r vdir; do
          vdir_name="${vdir##*/}"
          vdir_parent="${vdir%/*}"
          latest_link="${vdir_parent}/latest"
          if [ ! -L "$latest_link" ]; then
            ln -s "$vdir_name" "$latest_link"
            echo "  [SYMLINK] Created: ${latest_link} -> ${vdir_name}"
            (( count_symlinks_created++ ))
          else
            echo "  [SYMLINK] Already exists: ${latest_link} — skipping"
          fi
        done < <(find "$dst" -type d -name 'v[0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9]' | sort)
      fi

    else
      queue+=("$entry")
    fi

  done

done

echo ""
echo "--- Pass 1 complete ---"
echo "    Directories moved: ${count_dirs_moved}"
echo "    Symlinks created:  ${count_symlinks_created}"
echo ""

# -------------------------------------------------------
# PASS 2 — per-file fallback for remaining source files
#          and symlinks in directories that already exist
#          at the destination
# -------------------------------------------------------

echo "--- Pass 2: file-level moves (remaining source files) ---"
echo ""

# Processes one file: same decision logic (missing dest dir / skip-if-exists
# / overwrite-if-exists / plain move) and the same tagged log lines as the
# original serial loop. Run in parallel batches below via xargs -P, so it
# can't rely on shared counter variables (each worker is a separate
# process) — final counts are derived from the log's tagged lines instead,
# after the pass completes.
move_one_file() {
  local file="$1"
  local src_dir="${file%/*}"
  local filename="${file##*/}"
  local dst_dir="${src_dir/$source_path/$target_path}"
  local dst_file="${dst_dir}/${filename}"

  if [ ! -d "$dst_dir" ]; then
    # Should not occur after pass 1 — log it if it does
    echo "  [WARN] Destination directory does not exist: ${dst_dir}"
    echo "         ${file} was not moved."
  elif [ -e "${dst_file}" ] && [ "$overwrite" = false ]; then
    echo "  [SKIPPED] ${dst_file}"
  elif [ -e "${dst_file}" ] && [ "$overwrite" = true ]; then
    if [ "$dry_run" = false ]; then
      mv -f "${file}" "${dst_dir}/"
    fi
    echo "  [OVERWRITE] ${dst_file}"
  else
    if [ "$dry_run" = false ]; then
      mv "${file}" "${dst_dir}/"
    fi
    echo "  [MOVED] ${dst_file}"
  fi
}
export -f move_one_file
export source_path target_path overwrite dry_run

# Tunable via coordinator.sh; sane defaults if unset there.
pass2_parallel_jobs="${pass2_parallel_jobs:-8}"
pass2_batch_size="${pass2_batch_size:-100}"

# Dry run: prune dry_run_pruned_dirs out of this scan (see where it's
# populated in pass 1 above) — otherwise every file under a directory
# pass 1 already logged as "would move" gets re-scanned here and hits a
# nonsensical "destination missing" warning instead of being correctly
# treated as already handled. No-op (empty array) on a real run, where
# those directories are simply gone from source_path already.
find_prune_args=()
if [ "${#dry_run_pruned_dirs[@]}" -gt 0 ]; then
  find_prune_args+=("(")
  for d in "${dry_run_pruned_dirs[@]}"; do
    [ "${#find_prune_args[@]}" -gt 1 ] && find_prune_args+=("-o")
    find_prune_args+=("-path" "$d")
  done
  find_prune_args+=(")" "-prune" "-o")
fi

find "$source_path" "${find_prune_args[@]}" \( -type f -o -type l \) -print | sort | \
  xargs -P "$pass2_parallel_jobs" -n "$pass2_batch_size" bash -c '
    for file in "$@"; do
      move_one_file "$file"
    done
  ' _

count_files_moved=$(grep -c '^  \[MOVED\] ' "$log_file")
count_files_overwritten=$(grep -c '^  \[OVERWRITE\] ' "$log_file")
count_files_skipped=$(( $(grep -c '^  \[SKIPPED\] ' "$log_file") + $(grep -c '^  \[WARN\] ' "$log_file") ))

echo ""
echo "--- Pass 2 complete ---"
echo "    Moved:       ${count_files_moved}"
echo "    Overwritten: ${count_files_overwritten}"
echo "    Skipped:     ${count_files_skipped}"
echo ""

echo "Summary:"
echo "  Directories moved (pass 1): ${count_dirs_moved}"
echo "  Symlinks created  (pass 1): ${count_symlinks_created}"
echo "  Files moved       (pass 2): ${count_files_moved}"
echo "  Files overwritten (pass 2): ${count_files_overwritten}"
echo "  Files skipped     (pass 2): ${count_files_skipped}"
echo ""
echo "Completed ${myname} at $(date)"
